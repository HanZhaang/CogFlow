#!/usr/bin/env python
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Dict, List, Tuple

import numpy as np
import pandas as pd


ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts.cross_validation.ver2_dataset import default_cross_subject_path
try:
    from simactrat.state_models.base import BaseStateModel
    from simactrat.state_models.metrics import dwell_ks, state_nll, transition_js
except ImportError as exc:
    BaseStateModel = None
    _SIMACTRAT_IMPORT_ERROR = exc
else:
    _SIMACTRAT_IMPORT_ERROR = None


def ensure_dir(path: Path) -> Path:
    path.mkdir(parents=True, exist_ok=True)
    return path


def parse_csv_list(raw: str) -> List[str]:
    return [x.strip() for x in str(raw).split(",") if x.strip()]


def discover_splits(split_dir: Path, split_name: str = "") -> List[Path]:
    if not split_dir.exists():
        raise FileNotFoundError(f"split dir not found: {split_dir}")
    if str(split_name).strip():
        p = split_dir / str(split_name).strip()
        if not p.exists():
            raise FileNotFoundError(f"split not found: {p}")
        return [p]
    out = [p for p in sorted(split_dir.glob("loro_*")) if p.is_dir()]
    if not out:
        raise RuntimeError(f"no split found in {split_dir}")
    return out


def load_sequences(manifest_path: Path, min_len: int) -> Tuple[List[np.ndarray], int, List[str]]:
    df = pd.read_csv(manifest_path)
    if "state_path" not in df.columns:
        raise ValueError(f"manifest missing state_path: {manifest_path}")
    seqs: List[np.ndarray] = []
    total_frames = 0
    rats = sorted(df["rat_id"].astype(str).dropna().unique().tolist()) if "rat_id" in df.columns else []
    for _, row in df.iterrows():
        path = Path(str(row["state_path"]))
        if not path.exists():
            continue
        s = np.asarray(np.load(path, allow_pickle=True)).reshape(-1).astype(np.int32)
        s = s[s >= 0]
        if s.size < int(min_len):
            continue
        seqs.append(s)
        total_frames += int(s.size)
    return seqs, total_frames, rats


def sample_matched_sequences(
    model: BaseStateModel,
    real_sequences: List[np.ndarray],
    n_sim_per_trial: int,
    init_from_real: bool,
    seed: int,
) -> List[np.ndarray]:
    rng = np.random.default_rng(int(seed))
    out: List[np.ndarray] = []
    reps = max(1, int(n_sim_per_trial))
    for seq in real_sequences:
        T = int(seq.size)
        if T <= 0:
            continue
        for _ in range(reps):
            init_state = int(seq[0]) if init_from_real else None
            sample = model.sample_sequence(T=T, init_state=init_state, rng=rng)
            out.append(np.asarray(sample, dtype=np.int32).reshape(-1))
    return out


def evaluate_one_model(
    model_path: Path,
    model_name: str,
    real_sequences: List[np.ndarray],
    n_frames: int,
    args: argparse.Namespace,
) -> Tuple[Dict[str, object], List[Dict[str, object]]]:
    if _SIMACTRAT_IMPORT_ERROR is not None:
        raise ImportError(
            "state generalization evaluation requires simactrat to be installed; "
            f"original import error: {_SIMACTRAT_IMPORT_ERROR}"
        )
    model = BaseStateModel.load(model_path)
    n_states = int(getattr(model, "n_states", -1))
    if n_states <= 0:
        raise ValueError(f"invalid n_states in model: {model_path}")

    nll_frame = state_nll(model, real_sequences, normalize="frame")
    nll_segment = state_nll(model, real_sequences, normalize="segment")
    sim_sequences = sample_matched_sequences(
        model=model,
        real_sequences=real_sequences,
        n_sim_per_trial=int(args.n_sim_per_trial),
        init_from_real=bool(args.init_from_real),
        seed=int(args.seed),
    )
    if not sim_sequences:
        raise RuntimeError(f"no simulated sequence generated by {model_path}")

    dwell = dwell_ks(real_sequences, sim_sequences, n_states=n_states)
    trans = transition_js(
        real_sequences=real_sequences,
        sim_sequences=sim_sequences,
        n_states=n_states,
        laplace=float(args.transition_laplace),
    )

    row = {
        "model": model_name,
        "state_nll_frame": float(nll_frame),
        "state_nll_segment": float(nll_segment),
        "transition_js": float(trans["transition_js"]),
        "transition_js_rowavg": float(trans["transition_js_rowavg"]),
        "dwell_ks_macro": float(dwell["dwell_ks_macro"]),
        "dwell_ks_weighted": float(dwell["dwell_ks_weighted"]),
        "n_states": int(n_states),
        "n_test_trials": int(len(real_sequences)),
        "n_test_frames": int(n_frames),
        "n_sim_trials": int(len(sim_sequences)),
    }
    per_state = []
    for item in dwell["per_state"]:
        per_state.append(
            {
                "model": model_name,
                "state": int(item["state"]),
                "ks": float(item["ks"]),
                "n_real": int(item["n_real"]),
                "n_sim": int(item["n_sim"]),
            }
        )
    return row, per_state


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser("04_eval_state_generalization")
    p.add_argument("--split-dir", type=str, default=str(default_cross_subject_path("splits")))
    p.add_argument("--model-root", type=str, default=str(default_cross_subject_path("models")))
    p.add_argument("--out-dir", type=str, default=str(default_cross_subject_path("summary")))
    p.add_argument("--split-name", type=str, default="")
    p.add_argument("--models", type=str, default="mc,hmm,smp")
    p.add_argument("--min-len", type=int, default=2)
    p.add_argument("--n-sim-per-trial", type=int, default=1)
    p.add_argument("--init-from-real", action="store_true")
    p.add_argument("--transition-laplace", type=float, default=1e-6)
    p.add_argument("--seed", type=int, default=42)
    return p


def main() -> None:
    args = build_parser().parse_args()
    splits = discover_splits(Path(args.split_dir), split_name=str(args.split_name).strip())
    out_dir = ensure_dir(Path(args.out_dir))
    per_split_dir = ensure_dir(out_dir / "state_generalization")

    table_rows: List[Dict[str, object]] = []
    dwell_rows: List[Dict[str, object]] = []

    for split_path in splits:
        test_manifest = split_path / "test_manifest.csv"
        real_sequences, n_frames, test_rats = load_sequences(test_manifest, min_len=int(args.min_len))
        if not real_sequences:
            raise RuntimeError(f"{split_path.name}: no valid test state sequence")
        test_rat = ",".join(test_rats) if test_rats else ""

        model_dir = Path(args.model_root) / split_path.name / "state"
        if not model_dir.exists():
            raise FileNotFoundError(f"state model dir not found: {model_dir}")

        split_rows: List[Dict[str, object]] = []
        split_dwell_rows: List[Dict[str, object]] = []
        for name in parse_csv_list(args.models):
            model_path = model_dir / f"{name}.pkl"
            if not model_path.exists():
                raise FileNotFoundError(f"model not found: {model_path}")
            row, per_state = evaluate_one_model(
                model_path=model_path,
                model_name=name,
                real_sequences=real_sequences,
                n_frames=n_frames,
                args=args,
            )
            row["split"] = split_path.name
            row["test_rat"] = test_rat
            split_rows.append(row)
            for d in per_state:
                d["split"] = split_path.name
                d["test_rat"] = test_rat
                split_dwell_rows.append(d)

        split_out = ensure_dir(per_split_dir / split_path.name)
        pd.DataFrame(split_rows).to_csv(split_out / "state_metrics.csv", index=False)
        pd.DataFrame(split_dwell_rows).to_csv(split_out / "state_dwell_per_state.csv", index=False)
        table_rows.extend(split_rows)
        dwell_rows.extend(split_dwell_rows)
        print(f"[04] done split={split_path.name}, models={len(split_rows)}")

    main_table = pd.DataFrame(table_rows)
    per_state_table = pd.DataFrame(dwell_rows)
    main_path = per_split_dir / "table_state_generalization.csv"
    per_state_path = per_split_dir / "table_state_generalization_dwell_per_state.csv"
    main_table.to_csv(main_path, index=False)
    per_state_table.to_csv(per_state_path, index=False)
    with (per_split_dir / "eval_args.json").open("w", encoding="utf-8") as f:
        json.dump(vars(args), f, indent=2, ensure_ascii=True)
    print(f"[04] table: {main_path}")


if __name__ == "__main__":
    main()
